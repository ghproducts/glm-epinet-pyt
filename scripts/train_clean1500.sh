#!/usr/bin/env bash
# Train base + Epinet on the clean 1.5kb fragment benchmark (.docs/plans/TAXA_SHIFT_PLAN.md).
# usage: bash scripts/train_clean1500.sh <backbone> <phylum|family|gene_taxa> <seed> <gpu>
# (gene_taxa = the Scorpio gene-classification task: 437 gene labels, no taxonomic rank)
# Recipe: Adam, lr 2e-5, batch 32, full fine-tune with early stopping (decided 2026-10-13; the
# fixed 2-epoch recipe left models undertrained, see .docs/plans/TAXA_SHIFT_PLAN.md);
# Epinet lr 1e-3 on the frozen base. train_base holds out 10% of train.csv for
# checkpoint selection; temperature is fit separately on val.csv (held-out genome blocks).
# Completion is signalled by the ARTIFACT (a checkpoint dir), not process exit.
# Do not edit this file while runs are using it: bash reads scripts incrementally, so a running
# copy resumes at a shifted offset. Queue/long runs should execute a frozen copy (cp first).
set -uo pipefail
cd "$(dirname "$0")/.."
source /scratch/home/glh52/venvs/glm_epinet_venv/bin/activate
export PYTORCH_CUDA_ALLOC_CONF=expandable_segments:True
# Hugging Face datasets writes an Arrow copy of every CSV load / tokenized map; keep it off the 7 TB root disk
# (it had grown to 1.7 TB in ~/.cache/huggingface/datasets/csv and filled / on 2026-10-25)
export HF_DATASETS_CACHE=${HF_DATASETS_CACHE:-/scratch/home/glh52/.cache_hf_datasets}
B=$1; R=$2; S=$3; G=$4
# optional overrides: EPOCHS (base-model cap, default 20), CKPT_ROOT (default checkpoints/clean1500_es),
# PATIENCE (default 3; >0: base model evaluates every half epoch and stops after PATIENCE evaluations
# without eval-loss improvement; PATIENCE=0 EPOCHS=2 reproduces the old fixed-length recipe)
EPOCHS=${EPOCHS:-20}; CKPT_ROOT=${CKPT_ROOT:-checkpoints/clean1500_es}; PATIENCE=${PATIENCE:-3}
# MODEL_ID: pretrained hub id to fine-tune instead of the backbone default (e.g. the multi-species
# CARMANIA, MsAlEhR/carmania-big-10k-prok-genome); used for both the base model and the Epinet tokenizer
MODEL_ID=${MODEL_ID:-}
# Epinet: early stopping too (decided 2026-10-17; 2 fixed epochs left e.g. the multi-species CARMANIA
# gene-task head unconverged). EPI_EPOCHS = cap, EPI_PATIENCE = evaluations without improvement.
EPI_EPOCHS=${EPI_EPOCHS:-20}; EPI_PATIENCE=${EPI_PATIENCE:-3}
if [ "$R" = gene_taxa ]; then
  # ~930bp median, up to 13kb; cap at 3000bp (as in the earlier gene_taxa runs: NT 500 tokens)
  D=/scratch/home/glh52/glm-epinet/DATA/gene_taxa; N=437; DATA=(--data_path $D/train.csv --num_labels $N)
  case $B in NT_transformer) ML=500;; DNABERT2) ML=750;; hyenaDNA|CARMANIA) ML=3000;; esac
  HALF=7700    # 492,771 training rows / batch 32 = 15,399 steps per epoch
else
  D=/scratch/home/glh52/glm-epinet/DATA/clean1500
  case $R in phylum) N=43;; family) N=460;; *) echo bad rank; exit 1;; esac
  DATA=(--data_path $D/train.csv --taxa_df $D/full_basic_lineage.csv --taxa_rank $R --num_labels $N)
  case $B in NT_transformer) ML=256;; DNABERT2) ML=384;; hyenaDNA|CARMANIA) ML=1504;; esac
  HALF=3516    # 225k training fragments / batch 32 = 7,032 steps per epoch
fi
BS=32; GA=1
# CARMANIA at 3000 tokens runs out of memory at batch 32 (SDPA attention); same effective batch via accumulation
[ "$R" = gene_taxa ] && [ "$B" = CARMANIA ] && { BS=16; GA=2; }
OUT=$CKPT_ROOT/$B/$R/seed$S; LOG=logs/$(basename $CKPT_ROOT); mkdir -p $OUT $LOG
COMMON=("${DATA[@]}" ${MODEL_ID:+--model_name_or_path $MODEL_ID}
        --model_max_length $ML --per_device_train_batch_size $BS --per_device_eval_batch_size $BS --gradient_accumulation_steps $GA
        --fp16 --eval_strategy epoch --save_strategy epoch --save_total_limit 1
        --load_best_model_at_end True --warmup_steps 50 --logging_steps 500 --overwrite_output_dir True
        --find_unused_parameters False --seed $S --data_seed $S)
ES=()
[ "$PATIENCE" -gt 0 ] && ES=(--eval_strategy steps --eval_steps $HALF --save_strategy steps --save_steps $HALF
                            --early_stopping_patience $PATIENCE --metric_for_best_model eval_loss --greater_is_better False)
# EVIDENTIAL=1: train only the evidential model (Sensoy et al. 2018) into $OUT/evidential -- a separate
# full fine-tune from the pretrained backbone with the Dirichlet loss, same lr/batch/early stopping as the
# base model (its validation loss is computed at full KL weight; see train_evidential.py) -- then exit.
if [ "${EVIDENTIAL:-0}" = 1 ]; then
  echo "[$(date +%T)] evidential $B $R seed$S gpu$G epochs<=$EPOCHS patience=$PATIENCE"
  # (2026-10-27) the squared-error evidential loss collapses with 400+ classes; default to the digamma / cross-entropy
  # form (Sensoy et al. eq. 4) and early stopping on validation accuracy (the KL-weighted loss rewards collapse)
  EV_ES=("${ES[@]}"); [ "$PATIENCE" -gt 0 ] && EV_ES=(--eval_strategy steps --eval_steps $HALF --save_strategy steps --save_steps $HALF
      --early_stopping_patience $PATIENCE --metric_for_best_model ${EVID_METRIC:-eval_accuracy} --greater_is_better ${EVID_GREATER:-True})
  CUDA_VISIBLE_DEVICES=$G python -m nn_proj.models.$B.train_evidential "${COMMON[@]}" --learning_rate 2e-5 --num_train_epochs $EPOCHS "${EV_ES[@]}" \
    --evidential_loss_type ${EVID_LOSS:-ce} --annealing_step ${EVID_ANNEAL:-10} --kl_weight ${EVID_KL:-1.0} \
    --run_name c1500_evid_${B}_${R}_s$S --output_dir $OUT/evidential > $LOG/${B}_${R}_s${S}_evidential.log 2>&1
  ls -d $OUT/evidential/checkpoint-* >/dev/null 2>&1 && echo "[$(date +%T)] DONE evidential $B $R seed$S" \
    || echo "[$(date +%T)] FAILED evidential $B $R seed$S"
  exit 0
fi
# SKIP_BASE=1: base model already trained in $OUT/base (e.g. resuming after an interruption); go to the Epinet
[ "${SKIP_BASE:-0}" = 1 ] || { echo "[$(date +%T)] base $B $R seed$S gpu$G epochs<=$EPOCHS patience=$PATIENCE"
CUDA_VISIBLE_DEVICES=$G python -m nn_proj.models.$B.train_base "${COMMON[@]}" --learning_rate 2e-5 --num_train_epochs $EPOCHS "${ES[@]}" \
  --run_name c1500_${B}_${R}_s$S --output_dir $OUT/base > $LOG/${B}_${R}_s${S}_base.log 2>&1; }
# best checkpoint by eval loss (load_best_model_at_end keeps it alongside the last one)
LAST=$(ls -d $OUT/base/checkpoint-* 2>/dev/null | sort -V | tail -1)
CK=$([ -n "$LAST" ] && python -c "import json,sys; print(json.load(open('$LAST/trainer_state.json')).get('best_model_checkpoint') or '$LAST')")
[ -z "$CK" ] && { echo "[$(date +%T)] FAILED base $B $R seed$S"; exit 1; }
echo "[$(date +%T)] base done -> $CK; epinet"
EPI_ES=()
[ "$EPI_PATIENCE" -gt 0 ] && EPI_ES=(--eval_strategy steps --eval_steps $HALF --save_strategy steps --save_steps $HALF
                                    --early_stopping_patience $EPI_PATIENCE --metric_for_best_model eval_loss --greater_is_better False)
# PRIOR: relative Epinet prior scale (MLP and conv prior; EpinetConfig.relative_prior, chosen by the promoter sweep)
CUDA_VISIBLE_DEVICES=$G python -m nn_proj.models.$B.train_epinet "${COMMON[@]}" --learning_rate 1e-3 --num_train_epochs $EPI_EPOCHS "${EPI_ES[@]}" \
  ${PRIOR:+--prior_scale $PRIOR --conv_prior_scale $PRIOR} \
  --checkpoint $CK --run_name c1500_epi_${B}_${R}_s$S --output_dir $OUT/epinet > $LOG/${B}_${R}_s${S}_epinet.log 2>&1
EK=$(ls -d $OUT/epinet/checkpoint-* 2>/dev/null | sort -V | tail -1)
[ -z "$EK" ] && { echo "[$(date +%T)] FAILED epinet $B $R seed$S"; exit 1; }
echo "[$(date +%T)] DONE $B $R seed$S"
