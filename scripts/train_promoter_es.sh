#!/usr/bin/env bash
# Train base / Epinet / evidential on promoter_all for the aleatoric-boundary and AliSim UQ sweep
# (data_gen/uq_sweep), with the same early-stopping recipe as scripts/train_clean1500.sh.
# usage: bash scripts/train_promoter_es.sh <backbone> <base|epinet|evidential> <seed> <gpu>
# Recipe: lr 2e-5 (Epinet 1e-3 on the frozen base), batch 32, cap 20 epochs, evaluate every half
# epoch, stop after 3 evaluations without eval-loss improvement, keep the best checkpoint.
# Layout: $CKPT_ROOT/seed_<S>/<B>/label_noise_r00/<kind>_run/checkpoint-*, plus a <kind> symlink to
# the best checkpoint, which is what data_gen/uq_sweep loads (base, epinet_zfix, evidential).
# Do not edit this file while runs are using it: run a frozen copy.
set -uo pipefail
cd "${REPO:-$(dirname "$0")/..}"
source /scratch/home/glh52/venvs/glm_epinet_venv/bin/activate
export PYTORCH_CUDA_ALLOC_CONF=expandable_segments:True
# Hugging Face datasets writes an Arrow copy of every CSV load / tokenized map; keep it off the 7 TB root disk
# (it had grown to 1.7 TB in ~/.cache/huggingface/datasets/csv and filled / on 2026-10-25)
export HF_DATASETS_CACHE=${HF_DATASETS_CACHE:-/scratch/home/glh52/.cache_hf_datasets}
B=$1; K=$2; S=$3; G=$4
CKPT_ROOT=${CKPT_ROOT:-/scratch/home/glh52/glm-epinet-pyt/checkpoints/promoter_es}
DATA=${DATA:-/scratch/home/glh52/glm-epinet-pyt/data_gen/label_noise/csv_data_r00/train.csv}
EPOCHS=${EPOCHS:-20}; PATIENCE=${PATIENCE:-3}
HALF=422     # 27,000 training rows (90% of 30,000) / batch 32 = 844 steps per epoch
# model_max_length incl. special tokens, measured over train/test/AliSim (see data_gen/uq_sweep/retrain_base.sh)
case $B in NT_transformer) ML=52;; DNABERT2) ML=77;; hyenaDNA) ML=301;; CARMANIA) ML=300;; *) echo bad backbone; exit 1;; esac
D=$CKPT_ROOT/seed_$S/$B/label_noise_r00; LOG=logs/promoter_es; mkdir -p $D $LOG
TAG=${EPI_TAG:+_$EPI_TAG}
COMMON=(--data_path $DATA --num_labels 2 --model_max_length $ML --per_device_train_batch_size 32 --per_device_eval_batch_size 32
        --fp16 --save_total_limit 1 --load_best_model_at_end True --warmup_steps 50 --logging_steps 100
        --overwrite_output_dir True --find_unused_parameters False --seed $S --data_seed $S
        --num_train_epochs $EPOCHS --eval_strategy steps --eval_steps $HALF --save_strategy steps --save_steps $HALF
        --early_stopping_patience $PATIENCE --metric_for_best_model eval_loss --greater_is_better False)
best() {  # best checkpoint of a Trainer output dir (load_best_model_at_end keeps it)
  local last; last=$(ls -d $1/checkpoint-* 2>/dev/null | sort -V | tail -1); [ -z "$last" ] && return 1
  python -c "import json; print(json.load(open('$last/trainer_state.json')).get('best_model_checkpoint') or '$last')"
}
case $K in
  base)       MOD=train_base;     LR=2e-5; LINK=base;        EXTRA=() ;;
  epinet)     MOD=train_epinet;   LR=1e-3; LINK=${EPI_TAG:-epinet_zfix}
              BK=$(readlink -f $D/base); [ -d "$BK" ] || { echo "no base for $B seed$S"; exit 1; }
              # PRIOR: relative prior scale for both the MLP and the conv prior (EpinetConfig.relative_prior)
              # ablations: CONV_PRIOR (conv prior scale, default = PRIOR), INDEX_DIM, DET=1 (fixed index vector)
              EXTRA=(--checkpoint $BK ${PRIOR:+--prior_scale $PRIOR} --conv_prior_scale ${CONV_PRIOR:-${PRIOR:-1.0}}
                     ${INDEX_DIM:+--index_dim $INDEX_DIM} ${DET:+--deterministic_index True}) ;;
  evidential) MOD=train_evidential; LR=2e-5; LINK=evidential; EXTRA=() ;;
  *) echo bad kind; exit 1 ;;
esac
OUT=$D/${LINK}_run
echo "[$(date +%T)] $K $B seed$S gpu$G"
CUDA_VISIBLE_DEVICES=$G python -m nn_proj.models.$B.$MOD "${COMMON[@]}" "${EXTRA[@]}" --learning_rate $LR \
  --run_name prom_${K}_${B}_s$S$TAG --output_dir $OUT > $LOG/${B}_${K}${TAG}_s${S}.log 2>&1
CK=$(best $OUT) || { echo "[$(date +%T)] FAILED $K $B seed$S"; exit 1; }
ln -sfn $(basename $CK) $OUT/best && ln -sfn ${LINK}_run/best $D/$LINK
echo "[$(date +%T)] DONE $K $B seed$S -> $CK"
